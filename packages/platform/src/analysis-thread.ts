import { parentPort } from "node:worker_threads";
import { classifyIntent, classifyTopics } from "@aegis/ai-core";
import { MessageParseError, MessageTooLargeError, parseMail, type ParsedMail } from "@aegis/mail-parser";
import { analyzeWithFiles, BaselineScanner, ClamdScanner, extractAttachmentText, type MalwareScanner } from "@aegis/security-engine";
import { computePriority, type PriorityInput } from "./priority";

/**
 * Everything that touches attacker-controlled bytes in a regex or parser runs here, on a thread IsolatedPool can kill.
 * Results cross by structured clone, so Buffers arrive as Uint8Array and the caller rewraps them.
 */
export type AnalysisTask =
  | { op: "parse"; raw: Uint8Array }
  | { op: "analyze"; mail: ParsedMail; relationship: any; policy: any; scanner: { kind: "baseline" } | { kind: "clamd"; host: string; port: number } }
  | { op: "derive"; subject: string; text: string; isBulk: boolean; autoGenerated: boolean; customTopics: { name: string; terms: string[] }[]; priority: PriorityInput };

const rewrap = (m: ParsedMail): ParsedMail => ({ ...m, attachments: m.attachments.map(a => ({ ...a, content: Buffer.from(a.content) })) });

async function handle(t: AnalysisTask) {
  switch (t.op) {
    case "parse":
      try { return { ok: true, mail: await parseMail(Buffer.from(t.raw)) }; }
      catch (e) {
        if (e instanceof MessageTooLargeError || e instanceof MessageParseError) return { ok: false, unparseable: e.name };
        throw e;
      }
    case "analyze": {
      const mail = rewrap(t.mail);
      const scanner: MalwareScanner = t.scanner.kind === "clamd" ? new ClamdScanner(t.scanner.host, t.scanner.port) : new BaselineScanner();
      const { security, files } = await analyzeWithFiles(mail, mail.attachments, { relationship: t.relationship, policy: t.policy, scanner, attachmentTexts: mail.attachments.map(extractAttachmentText) });
      return { ok: true, security, files };
    }
    case "derive":
      return {
        ok: true,
        topics: classifyTopics(t.subject, t.text, t.isBulk, t.customTopics),
        intent: classifyIntent(t.subject, t.text, { isBulk: t.isBulk, autoGenerated: t.autoGenerated }),
        decision: computePriority({ ...t.priority, now: new Date(t.priority.now) }),
      };
  }
}

parentPort?.on("message", async (task: AnalysisTask) => {
  try { parentPort!.postMessage(await handle(task)); }
  catch (e) { parentPort!.postMessage({ ok: false, error: e instanceof Error ? e.name : "unknown" }); }
});
