/**
 * SCIM 2.0 users. Authenticated by a per-tenant bearer token, so there's no user and no RLS context: every query below
 * filters by the token's tenant. It reads people and memberships only. Nothing here touches mail, and nothing could: the web
 * login has no privilege on mail tables outside a user's context.
 */
const USER_SCHEMA = "urn:ietf:params:scim:schemas:core:2.0:User";
const LIST_SCHEMA = "urn:ietf:params:scim:api:messages:2.0:ListResponse";
const ERROR_SCHEMA = "urn:ietf:params:scim:api:messages:2.0:Error";
const PATCH_SCHEMA = "urn:ietf:params:scim:api:messages:2.0:PatchOp";
const sha = (s: string) => createHash("sha256").update(s).digest("hex");

export class ScimError extends Error {
  constructor(readonly status: number, detail: string, readonly scimType?: string) { super(detail); this.name = "ScimError"; }
  body() { return { schemas: [ERROR_SCHEMA], status: String(this.status), ...(this.scimType ? { scimType: this.scimType } : {}), detail: this.message }; }
}

export interface ScimAuth { tenantId: string; tokenId: string }

export async function authenticateScim(p: Platform, header: string | null, clientKey?: string): Promise<ScimAuth> {
  try { if (clientKey) await rateLimit(p, `scim-client:${sha(clientKey)}`, 600, 60); }
  catch (e) { if (e instanceof AppError && e.status === 429) throw new ScimError(429, "Too many requests."); throw e; }
  const m = /^Bearer\s+(\S+)$/i.exec(header ?? "");
  const row = m ? await p.db.withSystem(t => t.one<{ id: string; tenant_id: string }>("SELECT id, tenant_id FROM scim_token_lookup($1)", [sha(m[1]!)])) : null;
  if (!row) throw new ScimError(401, "A valid bearer token is required.");
  try { await rateLimit(p, `scim-token:${row.id}`, 1200, 60); }
  catch (e) { if (e instanceof AppError && e.status === 429) throw new ScimError(429, "Too many requests."); throw e; }
  return { tenantId: row.tenant_id, tokenId: row.id };
}

// ---------- Token management, in the app ----------
async function requireOrganization(p: Platform, ctx: Ctx) {
  await requireRole(p, ctx, "manageSso");
  const org = await p.db.withUser(ctx, t => t.one<{ kind: string }>("SELECT kind FROM organizations WHERE id=$1", [ctx.tenantId]));
  if (org?.kind !== "organization") throw badRequest("organization_only", "Provisioning is only available for organization workspaces.");
}

/** Revokes any current token. The new one is returned once and only its hash is kept. */
export async function rotateScimToken(p: Platform, ctx: Ctx) {
  await requireOrganization(p, ctx);
  const token = `aegis_scim_${randomToken(32)}`;
  await p.db.withUser(ctx, async t => {
    await t.query("UPDATE scim_tokens SET revoked_at=now() WHERE tenant_id=$1 AND revoked_at IS NULL", [ctx.tenantId]);
    await t.query("INSERT INTO scim_tokens(tenant_id,token_hash,created_by) VALUES ($1,$2,$3)", [ctx.tenantId, sha(token), ctx.userId]);
    await audit(t, { tenantId: ctx.tenantId, actor: ctx.userId, event: "scim.token_rotated" });
  });
  return { token, baseUrl: `${p.config.appOrigin}/api/v1/scim/v2` };
}

export async function revokeScimToken(p: Platform, ctx: Ctx) {
  await requireRole(p, ctx, "manageSso");
  await p.db.withUser(ctx, async t => {
    await t.query("UPDATE scim_tokens SET revoked_at=now() WHERE tenant_id=$1 AND revoked_at IS NULL", [ctx.tenantId]);
    await audit(t, { tenantId: ctx.tenantId, actor: ctx.userId, event: "scim.token_revoked" });
  });
}

