import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { computePriority, createLabel, type Ctx, listThreads, type Platform, ruleFromText, threadAction } from "../index";
import { deliver, demoAccount, testPlatform, user } from "./harness";

/** Smaller things the first real install turned up, 2026-11-09. */
describe("due dates on old mail", () => {
  const base = { subject: "Budget", isBulk: false, autoGenerated: false, fromMe: false, riskLabel: "safe" as const, received: 0, sentTo: 0, replied: 0, dismissed: 0, isVip: false, isIgnored: false, threadHasMyReply: false, personalizationEnabled: true };
  const now = new Date("2026-11-09T10:00:00Z");
  it("a date that passed weeks ago isn't today's commitment", () => {
    const old = computePriority({ ...base, text: "The invoice was placed on October 12.", now, sentAt: new Date("2026-10-13T10:00:00Z") });
    expect(old.section).not.toBe("todays_commitments");
  });
  it("'tomorrow' in a message from three weeks ago means the day after it was written", () => {
    const text = "I'll send the signed copy tomorrow.";
    expect(computePriority({ ...base, text, now, sentAt: new Date("2026-10-19T10:00:00Z") }).section).not.toBe("todays_commitments");
    expect(computePriority({ ...base, text, now, sentAt: now }).section).toBe("todays_commitments");
  });
});

describe("a rule typed in plain words", () => {
  it("that's understood but out of range gets a message, not a server error", () => {
    const r = ruleFromText("remind me in 60 days about invoices from acme.com");
    expect(r).toHaveProperty("error");
    expect(ruleFromText("remind me in 2 days about invoices from acme.com")).toHaveProperty("definition");
  });
});

describe("list views", () => {
  let p: Platform, drop: () => Promise<void>, ctx: Ctx, acc: string;
  beforeAll(async () => {
    ({ p, drop } = await testPlatform());
    ctx = await user(p, "views@fernhill.example");
    acc = await demoAccount(p, ctx, "views@fernhill.example");
  });
  afterAll(async () => { await drop(); });

  it("a label shows everything it's on, archived mail included", async () => {
    const l = await createLabel(p, ctx, acc, "Invoices", "#123456");
    const kept = await deliver(p, ctx, acc, { from: `"A" <a@oak.example>`, subject: "Invoice one", text: "Attached." });
    const filed = await deliver(p, ctx, acc, { from: `"B" <b@oak.example>`, subject: "Invoice two", text: "Attached." });
    for (const m of [kept, filed]) await threadAction(p, ctx, m.thread_id, { action: "label", labelId: l.id });
    await threadAction(p, ctx, filed.thread_id, { action: "archive" });
    const shown = await listThreads(p, ctx, { view: "inbox", labelId: l.id, limit: 10 });
    expect(shown.items.map(i => i.subject).sort()).toEqual(["Invoice one", "Invoice two"]);
  });

  it("awaiting reply leaves out conversations that were answered", async () => {
    const mine = { from: `"Me" <views@fernhill.example>`, to: "c@oak.example" };
    await deliver(p, ctx, acc, { ...mine, subject: "Open question", text: "Any news?", messageId: "<open@fernhill>" }, { folder: "sent", thread: "t-open", hoursAgo: 5 });
    await deliver(p, ctx, acc, { ...mine, subject: "Closed question", text: "Any news?", messageId: "<closed@fernhill>" }, { folder: "sent", thread: "t-closed", hoursAgo: 5 });
    await deliver(p, ctx, acc, { from: `"C" <c@oak.example>`, subject: "Re: Closed question", text: "Yes, done.", inReplyTo: "<closed@fernhill>" }, { thread: "t-closed", hoursAgo: 1 });
    const waiting = await listThreads(p, ctx, { view: "awaiting", limit: 10 });
    expect(waiting.items.map(i => i.subject)).toEqual(["Open question"]);
  });
});
