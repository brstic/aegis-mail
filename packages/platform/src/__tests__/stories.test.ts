    it("explains itself in human language, with the evidence for dates", () => {
      const d = computePriority({ ...base, subject: "Scope", text: "Can you send the budget by November 11?", riskLabel: "safe" });
      expect(d.section).toBe("needs_attention");
      expect(d.reasons.join(" ")).toMatch(/direct question/);
      expect(d.due?.evidence).toMatch(/November 11/);
      expect(d.due?.uncertain).toBe(false);
    });
    it("vague timing is marked uncertain", () => {
      const d = computePriority({ ...base, subject: "Copy", text: "Please take a look soon.", riskLabel: "safe" });
      expect(d.due).toMatchObject({ uncertain: true, iso: undefined });
    });
    it("opting out of personalization removes relationship signals", () => {
      const on = computePriority({ ...base, subject: "Hi", text: "Hello there.", riskLabel: "safe" });
      const off = computePriority({ ...base, subject: "Hi", text: "Hello there.", riskLabel: "safe", personalizationEnabled: false });
      expect(off.features.relationship).toBe(0);
      expect(on.features.relationship).toBeGreaterThan(0);
    });
