      expect(pr.action.type).toBe("archive");
      await decideProposal(p, ctx, pr.id, true);
      expect((await p.db.withWorker(ctx.tenantId, t => t.one<any>("SELECT folder_role, is_starred FROM messages WHERE id=$1", [m.id])))).toEqual({ folder_role: "archive", is_starred: true });
