    expect((await seedDemo(p)).created).toBe(false);
    const s = await signIn(p, { email: DEMO_LOGIN.email, password: DEMO_LOGIN.password });
    const session = await resolveSession(p, s.token);
    const ctx = { tenantId: session!.tenantId, userId: session!.userId };
    const f = await getFocus(p, ctx);
    const by = Object.fromEntries(f.sections.map(x => [x.key, x.items.map(i => i.subject)]));
    // Blocked mail stays out of Focus. It waits in Blocked, and only mail we aren't sure about is shown for a second look.
    expect(Object.values(by).flat().join("|")).not.toMatch(/updated bank details/);
    expect((await listThreads(p, ctx, { view: "quarantine", limit: 50 })).items.map(i => i.subject).join("|")).toMatch(/updated bank details/);
    expect(by.security_review!.join("|")).toMatch(/Partnership idea|Contract pack/);
    expect(Object.values(by).flat().join("|")).not.toMatch(/password expires/);
    expect(by.needs_attention!.join("|")).toMatch(/scope for phase two|Contract renewal/);
    expect(by.low_priority!.join("|")).toMatch(/type systems|Pricing|Markets/);
    expect(by.waiting_on_someone!.join("|")).toMatch(/Tallgrass|logo/);
    // Thread of three stays together.
    const oak = f.sections.flatMap(x => x.items).find(i => i.subject.includes("phase two"))!;
    expect(oak.count).toBe(3);
    await simulateIncoming(p, ctx, 0);
    await drainJobs(p);
    const after = await listThreads(p, ctx, { view: "inbox", q: "signage", limit: 5 });
