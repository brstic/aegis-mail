import { DEFAULT_PRIORITY_WEIGHTS, type FocusSection, type PriorityDecision, type PriorityFeatures, type PriorityWeights, type RiskLabel } from "@aegis/domain";
import { businessContext, classifyIntent, explicitUrgency, extractActions, extractDue, type ActionItem } from "@aegis/ai-core";

export const PRIORITY_VERSION = "prio-2026.11.1";

export interface PriorityInput {
  subject: string;
  text: string;
  fromName?: string;
  riskLabel: RiskLabel;
  isBulk: boolean;
  autoGenerated: boolean;
  fromMe: boolean;
  received: number; sentTo: number; replied: number; dismissed: number;
  isVip: boolean; isIgnored: boolean;
  threadHasMyReply: boolean;
  userBoost?: number;
  /** The owner lowered this whole account. */
  accountPenalty?: number;
  personalizationEnabled: boolean;
  weights?: Partial<PriorityWeights>;
  now: Date;
  /** When the message was written. Relative dates in it ("by tomorrow") are read from here. */
  sentAt?: Date;
}

const clamp = (v: number) => Math.max(0, Math.min(1, v));
const FLAGGED: RiskLabel[] = ["suspicious", "high_risk", "malicious", "unknown_unscannable"];

/** Bounded, explainable. Bounded features mean no single word (say "URGENT") can dominate. */
export function computePriority(i: PriorityInput): PriorityDecision & { actions: ActionItem[] } {
  const w = { ...DEFAULT_PRIORITY_WEIGHTS, ...i.weights };
  const actions = i.fromMe ? [] : extractActions("self", i.text, false, i.now);
  // "Tomorrow" means the day after the message was written, not the day after it was synced.
  const due = extractDue(`${i.subject}\n${i.text}`, i.sentAt ?? i.now);
  const intent = classifyIntent(i.subject, i.text, { isBulk: i.isBulk, autoGenerated: i.autoGenerated });
  const needsReply = !i.fromMe && !i.isBulk && !i.autoGenerated && (intent === "question" || intent === "request");

  let deadline = 0;
  if (due?.iso) {
    const hours = (new Date(due.iso).getTime() - i.now.getTime()) / 36e5;
    deadline = hours < -24 ? 0.2 : hours <= 48 ? 1 : hours <= 24 * 7 ? 0.75 : 0.4;
  } else if (due?.uncertain) deadline = 0.3;

  const p = i.personalizationEnabled;
  const features: PriorityFeatures = {
    relationship: p ? clamp((i.isVip ? 0.6 : 0) + Math.min(i.sentTo, 5) * 0.08 + Math.min(i.received, 20) * 0.015) : 0,
    explicit_urgency: explicitUrgency(i.subject, i.text),
    deadline,
    thread_state: needsReply ? (i.threadHasMyReply ? 1 : 0.8) : 0,
    business_context: businessContext(i.subject, i.text),
    historical_response: p ? clamp(i.received ? i.replied / i.received : 0) : 0,
    user_rules: clamp(i.userBoost ?? 0),
    bulk_noise: i.isBulk ? 1 : i.autoGenerated ? 0.6 : 0,
    recently_dismissed: clamp((p ? (i.isIgnored ? 1 : 0) + Math.min(i.dismissed, 4) * 0.2 : 0) + (i.accountPenalty ?? 0)),
  };
  const raw = w.relationship * features.relationship + w.explicit_urgency * features.explicit_urgency + w.deadline * features.deadline + w.thread_state * features.thread_state
    + w.business_context * features.business_context + w.historical_response * features.historical_response + w.user_rules * features.user_rules
    - w.bulk_noise * features.bulk_noise - w.recently_dismissed * features.recently_dismissed;
  let score = clamp(raw);

  // Threat policy runs first and can't be overridden: a scam never climbs because it says URGENT or CEO.
  const flagged = FLAGGED.includes(i.riskLabel);
  if (flagged) score = 0;

  const reasons: string[] = [];
  let section: FocusSection;
  if (flagged) { section = "security_review"; reasons.push("Not sure about this one. Check who sent it before you act."); }
  else {
    if (i.isVip) reasons.push("You marked this sender as important.");
    else if (features.relationship >= 0.3) reasons.push("You regularly correspond with this sender.");
    if (needsReply) reasons.push(intent === "question" ? "It asks you a direct question." : "It asks you to do something.");
    if (i.threadHasMyReply && needsReply) reasons.push("You're already in this conversation and it's waiting on you.");
    if (due?.iso) reasons.push(`It mentions a date: "${due.text}".`);
    else if (due?.uncertain) reasons.push(`It suggests timing, but only loosely: "${due.text}".`);
    if (features.business_context >= 0.6) reasons.push("It concerns business matters like contracts, budgets or decisions.");
    if (features.user_rules > 0) reasons.push("You raised the priority of this account.");
    if ((i.accountPenalty ?? 0) > 0) reasons.push("You lowered the priority of this account.");
    if (i.isIgnored) reasons.push("You asked to see less from this sender.");
    if (i.isBulk) reasons.push("It's a newsletter or bulk mail.");
    else if (i.autoGenerated) reasons.push("It's an automated notification.");

    // Due within two days, and not already more than a day past: a first sync brings in weeks of mail whose dates have gone.
    const dueIn = due?.iso ? (new Date(due.iso).getTime() - i.now.getTime()) / 36e5 : NaN;
    const dueSoon = dueIn >= -24 && dueIn <= 48;
    if (i.isIgnored || i.isBulk) section = "low_priority";
    else if (i.autoGenerated) section = "low_priority";
    else if (needsReply && score >= 0.28) section = "needs_attention";
    else if (dueSoon && !i.fromMe) section = "todays_commitments";
    else if (i.isVip || features.relationship >= 0.3) section = "important_people";
    else if (needsReply) section = "needs_attention";
    else section = "read_later";
    if (!reasons.length) reasons.push("Nothing here needs you right away.");
  }

  // Confidence reflects how much evidence supports the ranking, not a claim about accuracy.
  const evidenceCount = Object.values(features).filter(v => v > 0).length;
  const confidence = flagged ? 0.9 : clamp(0.45 + evidenceCount * 0.1);

  return {
    score, section, confidence, features, reasons, needsReply: needsReply && !flagged, version: PRIORITY_VERSION, actions,
    // A date in flagged mail is the attacker's manufactured urgency, not a deadline to show.
    due: due && !flagged ? { text: due.text, iso: due.iso, uncertain: due.uncertain, evidence: due.evidence } : undefined,
  };
}
