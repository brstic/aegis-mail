let pool: IsolatedPool | null = null;
/** One pool per process. Time and memory limits apply per task. */
function analysisPool() {
  return (pool ??= new IsolatedPool(new URL("./analysis-thread.ts", import.meta.url), { size: Number(process.env.WORKER_CONCURRENCY ?? 4), timeoutMs: Number(process.env.AEGIS_ANALYSIS_TIMEOUT_MS ?? 30_000) }));
}
export async function closeAnalysisPool() { await pool?.close(); pool = null; }

/** Custom scanners can't cross a thread boundary; the built-in ones are configuration. */
function scannerConfig(p: Platform) {
  if (p.scanner instanceof ClamdScanner) return { kind: "clamd" as const, host: p.scanner.host, port: p.scanner.port };
  if (p.scanner instanceof BaselineScanner) return { kind: "baseline" as const };
  return null;
}
