import { extractDue, type DueInfo } from "./dates";

export type Intent = "request" | "question" | "fyi" | "notification" | "promotion";
export interface ActionItem { text: string; kind: "question" | "request" | "promise"; owner: "you" | "them"; due?: DueInfo; messageId: string }

const TOPIC_RULES: [string, RegExp][] = [
  ["invoices", /\b(invoice|remittance|purchase order|\bpo-?\d+|receipt|statement|payment (of|due))\b/i],
  ["finance", /\b(budget|bank|wire|payroll|tax|accounting|expense|funding|term sheet)\b/i],
  ["legal", /\b(contract|nda|agreement|redline|retainer|terms|counsel|legal)\b/i],
  ["meetings", /\b(meeting|call|calendar|reschedul\w+|agenda|appointment|availability|standup)\b/i],
  ["travel", /\b(flight|boarding|e-?ticket|hotel|itinerary|booking reference|train)\b/i],
  ["hr", /\b(offer letter|onboarding|benefits|recruit\w*|candidate|payslip|leave request)\b/i],
  ["sales", /\b(proposal|quote|pricing|prospect|renewal|demo|deal)\b/i],
  ["support", /\b(ticket|bug|issue|outage|support request|helpdesk)\b/i],
  ["alerts", /\b(alert|sign-?in|security notice|pull request|build failed|verification code|notification)\b/i],
  ["newsletter", /\b(newsletter|digest|this week|unsubscribe|issue #?\d+)\b/i],
];

export function classifyTopics(subject: string, text: string, isBulk: boolean, custom: { name: string; terms: string[] }[] = []): string[] {
  const h = `${subject}\n${text}`.slice(0, 8000);
  const lower = h.toLowerCase();
  // The user's own topics come first, and are plain word matches they can read and edit.
  const mine = custom.filter(c => c.terms.some(t => t && lower.includes(t.toLowerCase()))).map(c => c.name);
  const out = [...mine, ...TOPIC_RULES.filter(([, r]) => r.test(h)).map(([t]) => t)];
  if (isBulk && !out.includes("newsletter")) out.push("newsletter");
  return out.slice(0, 3);
}

const stripQuoted = (t: string) => {
  const lines = t.split(/\r?\n/);
  const cut = lines.findIndex(l => /^on .{5,120} wrote:\s*$/i.test(l.trim()) || /^-{2,}\s*(original|forwarded) message/i.test(l.trim()));
  return (cut >= 0 ? lines.slice(0, cut) : lines).filter(l => !l.trim().startsWith(">")).join("\n");
};

export function sentences(t: string): string[] {
  return stripQuoted(t).replace(/\r/g, "").split(/\n{2,}|(?<=[.!?])\s+|\n(?=[A-Z-•*])/)
    .map(s => s.replace(/\s+/g, " ").trim()).filter(s => s.length > 3 && s.length < 400);
}

const SIGNOFF = /^(thanks|thank you|best|regards|cheers|sincerely|kind regards|hi|hello|hey|dear)\b[^.?!]{0,40}[,.!]?$/i;
const REQUEST = /\b(can you|could you|would you|will you|please|need you to|let me know|send (me|over|us)|confirm|review|take a look|get back to|what do you think|do you want|are you able|kindly)\b/i;
const PROMISE = /\b(i'?ll|i will|we'?ll|we will|i can send|i'?m going to)\s+(send|share|get|follow|include|forward|review|call|update|have)\b/i;

// "Hi Morgan, could you…" on one line: the greeting isn't part of the task.
const GREETING = /^(hi|hello|hey|dear|morning|good (morning|afternoon|evening))\b[^,.!?]{0,30},\s+/i;
const withoutGreeting = (s: string) => { const t = s.replace(GREETING, ""); return t === s ? s : t.charAt(0).toUpperCase() + t.slice(1); };

export function extractActions(messageId: string, text: string, fromMe: boolean, ref: Date): ActionItem[] {
  const out: ActionItem[] = [];
  for (const raw of sentences(text)) {
    const s = withoutGreeting(raw);
    if (SIGNOFF.test(s)) continue;
    const due = extractDue(s, ref) ?? undefined;
    if (fromMe) {
      if (PROMISE.test(s)) out.push({ text: s, kind: "promise", owner: "you", due, messageId });
      continue;
    }
    if (/\?\s*$/.test(s) && !/\b(no rush\?)\b/i.test(s)) out.push({ text: s, kind: "question", owner: "you", due, messageId });
    else if (REQUEST.test(s) && !/\b(if you have|feel free|please find|please see|please note)\b/i.test(s)) out.push({ text: s, kind: "request", owner: "you", due, messageId });
  }
  return out.slice(0, 8);
}

export function classifyIntent(subject: string, text: string, opts: { isBulk: boolean; autoGenerated: boolean }): Intent {
  if (opts.isBulk) return /\b(off|sale|deal|discount|shop|% )\b/i.test(subject) ? "promotion" : "notification";
  if (opts.autoGenerated) return "notification";
  const items = extractActions("x", text, false, new Date());
  if (items.some(i => i.kind === "question")) return "question";
  if (items.some(i => i.kind === "request")) return "request";
  if (/^\s*(fyi|heads up)\b/i.test(`${subject} ${text}`) || /\bfyi\b/i.test(text)) return "fyi";
  return "fyi";
}

export function explicitUrgency(subject: string, text: string): number {
  const h = `${subject}\n${text}`.slice(0, 4000);
  let s = 0;
  if (/\b(urgent(ly)?|asap|immediately|time[- ]sensitive)\b/i.test(h)) s += 0.7;
  if (/\b(today|tonight|by end of day|eod|right away)\b/i.test(h)) s += 0.3;
  return Math.min(1, s);
}

export function businessContext(subject: string, text: string): number {
  const h = `${subject}\n${text}`.slice(0, 4000);
  let s = 0;
  if (/\b(contract|proposal|scope|budget|board|client|renew\w*|retainer|purchase order|decision)\b/i.test(h)) s += 0.6;
  if (/\$\s?\d|\b\d[\d,.]*\s?(usd|eur|gbp)\b/i.test(h)) s += 0.2;
  if (/\b(deadline|due|signed|sign-off|approval|approve)\b/i.test(h)) s += 0.2;
  return Math.min(1, s);
}
